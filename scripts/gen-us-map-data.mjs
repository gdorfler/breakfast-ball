// Generates src/lib/us-map-data.ts from the us-atlas pre-projected states TopoJSON.
// Run: node scripts/gen-us-map-data.mjs
// Only needs re-running if we ever want a different resolution or projection.
//
// The atlas is pre-projected with d3.geoAlbersUsa().scale(1300).translate([487.5, 305])
// into a 975x610 viewport — course dots must use that exact projection (see
// src/lib/map-projection.ts) so they land on the right spot.

import { writeFileSync } from "node:fs";
import { geoPath } from "d3-geo";
import * as topojson from "topojson-client";

const ATLAS_URL = "https://cdn.jsdelivr.net/npm/us-atlas@3/states-albers-10m.json";

const res = await fetch(ATLAS_URL);
if (!res.ok) throw new Error(`Failed to fetch atlas: HTTP ${res.status}`);
const us = await res.json();

const path = geoPath(); // identity projection — the atlas is already projected

const nationPath = path(topojson.feature(us, us.objects.nation));
// Interior borders only (shared edges between two states) — drawn as hairlines.
const statesMeshPath = path(topojson.mesh(us, us.objects.states, (a, b) => a !== b));

const out = `// AUTO-GENERATED by scripts/gen-us-map-data.mjs — do not edit by hand.
// Source: us-atlas@3 states-albers-10m.json (pre-projected AlbersUSA, 975x610).

export const US_MAP_VIEWBOX = { width: 975, height: 610 };

export const US_NATION_PATH = ${JSON.stringify(nationPath)};

export const US_STATES_MESH_PATH = ${JSON.stringify(statesMeshPath)};
`;

writeFileSync(new URL("../src/lib/us-map-data.ts", import.meta.url), out);
console.log(
  `Wrote src/lib/us-map-data.ts (nation ${Math.round(nationPath.length / 1024)}KB, mesh ${Math.round(statesMeshPath.length / 1024)}KB)`,
);
